#!/usr/bin/env node
// AX-01: generate the TypeScript and Python card types from card.schema.json.
//
//   node scripts/gen-card-types.mjs          write both files
//   node scripts/gen-card-types.mjs --check  exit 1 if either checked-in file is stale
//
// The generator understands only the schema shapes card.schema.json uses: objects with
// properties, arrays, enums, const, and type unions with null. The staleness test
// (src/assistant/cards/generated.test.ts) imports generate() and compares in memory.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
export const APP_DIR = resolve(HERE, '..')
export const REPO_DIR = resolve(APP_DIR, '..')
export const SCHEMA_FILE = resolve(APP_DIR, 'src/assistant/cards/card.schema.json')
export const TS_FILE = resolve(APP_DIR, 'src/assistant/cards/card.types.ts')
export const PY_FILE = resolve(REPO_DIR, 'scripts/assistant_cards/card_types.py')

/** Nested objects that become named types. Key: top-level property; value: type name. */
const NAMED_OBJECTS = {
  n: 'CardN',
  interval: 'CardInterval',
  scope: 'CardScope',
  source: 'CardSource',
  versions: 'CardVersions',
  page: 'CardPage',
  policy_fields: 'CardPolicyFields',
}

/** Enums that become named aliases. Key: dotted path from the root. */
const NAMED_ENUMS = {
  label: 'CardLabel',
  'n.unit': 'NUnit',
  'interval.kind': 'IntervalKind',
  sample: 'CardSample',
  status: 'CardStatus',
}

const HEADER = 'Generated by app/scripts/gen-card-types.mjs from app/src/assistant/cards/card.schema.json. Do not edit.'

function types(node) {
  const t = node.type
  return Array.isArray(t) ? t : t ? [t] : []
}

function enumAt(schema, path) {
  let node = schema
  for (const k of path.split('.')) node = node.properties[k]
  return node.enum
}

// ---------- TypeScript ----------

function tsScalar(t) {
  return { number: 'number', integer: 'number', string: 'string', boolean: 'boolean', null: 'null' }[t]
}

function tsType(node, path) {
  if (NAMED_ENUMS[path]) return NAMED_ENUMS[path]
  if (node.const !== undefined) return JSON.stringify(node.const)
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(' | ')
  const ts = types(node)
  const parts = ts.map((t) => {
    if (t === 'object') {
      if (NAMED_OBJECTS[path]) return NAMED_OBJECTS[path]
      if (node.additionalProperties && typeof node.additionalProperties === 'object') {
        return `Record<string, ${tsType(node.additionalProperties, `${path}.*`)}>`
      }
      return 'Record<string, unknown>'
    }
    if (t === 'array') return `${tsType(node.items, `${path}[]`)}[]`
    return tsScalar(t)
  })
  return parts.join(' | ')
}

function tsInterface(name, node, path, description) {
  const req = new Set(node.required ?? [])
  const lines = []
  if (description) lines.push(`/** ${description} */`)
  lines.push(`export interface ${name} {`)
  for (const [k, child] of Object.entries(node.properties)) {
    const p = path ? `${path}.${k}` : k
    if (child.description) lines.push(`  /** ${child.description} */`)
    lines.push(`  ${k}${req.has(k) ? '' : '?'}: ${tsType(child, p)}`)
  }
  lines.push('}')
  return lines.join('\n')
}

export function generateTs(schema) {
  const out = [`// ${HEADER}`, '']
  for (const [path, name] of Object.entries(NAMED_ENUMS)) {
    const values = enumAt(schema, path)
    out.push(`export const ${name.replace(/^./, (c) => c.toLowerCase())}Values = ${JSON.stringify(values)} as const`)
    out.push(`export type ${name} = (typeof ${name.replace(/^./, (c) => c.toLowerCase())}Values)[number]`)
    out.push('')
  }
  for (const [prop, name] of Object.entries(NAMED_OBJECTS)) {
    out.push(tsInterface(name, schema.properties[prop], prop, schema.properties[prop].description))
    out.push('')
  }
  out.push(tsInterface('Card', schema, '', schema.description))
  out.push('')
  return out.join('\n')
}

// ---------- Python ----------

function pyScalar(t) {
  return { number: 'float', integer: 'int', string: 'str', boolean: 'bool', null: 'None' }[t]
}

function pyType(node, path) {
  if (NAMED_ENUMS[path]) return NAMED_ENUMS[path]
  if (node.const !== undefined) return `Literal[${JSON.stringify(node.const)}]`
  if (node.enum) return `Literal[${node.enum.map((v) => JSON.stringify(v)).join(', ')}]`
  const ts = types(node)
  const parts = ts.map((t) => {
    if (t === 'object') {
      if (NAMED_OBJECTS[path]) return NAMED_OBJECTS[path]
      if (node.additionalProperties && typeof node.additionalProperties === 'object') {
        return `Dict[str, ${pyType(node.additionalProperties, `${path}.*`)}]`
      }
      return 'Dict[str, Any]'
    }
    if (t === 'array') return `List[${pyType(node.items, `${path}[]`)}]`
    return pyScalar(t)
  })
  const nonNull = parts.filter((p) => p !== 'None')
  const base = nonNull.length > 1 ? `Union[${nonNull.join(', ')}]` : nonNull[0]
  return parts.includes('None') ? `Optional[${base}]` : base
}

function pyClass(name, node, path, description) {
  const req = new Set(node.required ?? [])
  const keys = Object.keys(node.properties)
  const total = keys.every((k) => req.has(k))
  const allOptional = keys.every((k) => !req.has(k))
  if (!total && !allOptional) throw new Error(`${name}: mixed required and optional keys are not supported`)
  const lines = [`class ${name}(TypedDict${total ? '' : ', total=False'}):`]
  if (description) lines.push(`    """${description}"""`, '')
  for (const [k, child] of Object.entries(node.properties)) {
    lines.push(`    ${k}: ${pyType(child, path ? `${path}.${k}` : k)}`)
  }
  return lines.join('\n')
}

export function generatePy(schema) {
  const out = [
    `# ${HEADER}`,
    '"""AX-01 assistant card types (Python side, for the export and card builder scripts)."""',
    'from typing import Any, Dict, List, Literal, Optional, TypedDict, Union',
    '',
    '',
  ]
  for (const [path, name] of Object.entries(NAMED_ENUMS)) {
    const values = enumAt(schema, path)
    out.push(`${name} = Literal[${values.map((v) => JSON.stringify(v)).join(', ')}]`)
  }
  out.push('', '')
  for (const [prop, name] of Object.entries(NAMED_OBJECTS)) {
    out.push(pyClass(name, schema.properties[prop], prop, schema.properties[prop].description))
    out.push('', '')
  }
  out.push(pyClass('Card', schema, '', schema.description))
  out.push('')
  return out.join('\n')
}

export function generate(schema = JSON.parse(readFileSync(SCHEMA_FILE, 'utf8'))) {
  return { ts: generateTs(schema), py: generatePy(schema) }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const { ts, py } = generate()
  if (process.argv.includes('--check')) {
    const stale = [
      [TS_FILE, ts],
      [PY_FILE, py],
    ].filter(([f, want]) => {
      try {
        return readFileSync(f, 'utf8') !== want
      } catch {
        return true
      }
    })
    for (const [f] of stale) console.error(`stale: ${f}`)
    process.exit(stale.length ? 1 : 0)
  }
  writeFileSync(TS_FILE, ts)
  writeFileSync(PY_FILE, py)
  console.log(`wrote ${TS_FILE}\nwrote ${PY_FILE}`)
}
