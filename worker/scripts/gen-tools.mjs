#!/usr/bin/env node
// AX-08: generate worker/src/generated/tools.ts (SYSTEM_PROMPT, TOOLS, CATALOGUE_VERSION) from the
// exported catalogue, so the Worker and the app cannot disagree (design P7).
//
//   node scripts/gen-tools.mjs [--data <dir>] [--system <md>] [--tools <json>] [--playbook <json>] [--out <ts>] [--check]
//
// --data (default ../app/public/data) must hold assistant/catalogue.json and assistant/index.json
// (card kinds). --check regenerates in memory and exits 1 when the file on disk differs.
// Token bounds use ceil(chars / 4): tool schemas <= 1,400, catalogue section <= 600, system.md <= 1,200.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
export const LIMITS = { tools: 1400, catalogue: 600, system: 1200 }
const est = (s) => Math.ceil(s.length / 4)

function fill(node, ctx) {
  if (Array.isArray(node)) return node.map((n) => fill(n, ctx)).filter((n) => n !== undefined)
  if (node && typeof node === 'object') {
    const marker = node['x-fill']
    if (marker) {
      const values = ctx[marker]
      if (!values || !values.length) return undefined
      const { ['x-fill']: _drop, ...rest } = node
      return { ...rest, enum: values }
    }
    const out = {}
    for (const [k, v] of Object.entries(node)) {
      const f = fill(v, ctx)
      if (f !== undefined) out[k] = f
    }
    return out
  }
  return node
}

export function generate({ dataDir, systemPath, toolsPath, playbookPath }) {
  const catPath = join(dataDir, 'assistant', 'catalogue.json')
  const idxPath = join(dataDir, 'assistant', 'index.json')
  if (!existsSync(catPath)) throw new Error(`gen-tools: ${catPath} not found (run make app-data)`)
  if (!existsSync(idxPath)) throw new Error(`gen-tools: ${idxPath} not found (run build-cards --stage)`)
  const cat = JSON.parse(readFileSync(catPath, 'utf8'))
  const idx = JSON.parse(readFileSync(idxPath, 'utf8'))
  if (!cat.catalogue_version) throw new Error('gen-tools: catalogue.json has no catalogue_version')
  const views = cat.views.map((v) => v.name).sort()
  const cardKinds = [...new Set(idx.kinds.map((k) => k.kind))].sort()
  let bundles = []
  if (playbookPath && existsSync(playbookPath)) {
    const pb = JSON.parse(readFileSync(playbookPath, 'utf8'))
    const list = Array.isArray(pb) ? pb : pb.types ?? []
    // AX-21: a type with bundle:false has no card recipe and is not a bundle value.
    bundles = list.filter((t) => typeof t === 'string' || t.bundle !== false).map((t) => (typeof t === 'string' ? t : t.type ?? t.id)).filter(Boolean).sort()
  }
  const tpl = JSON.parse(readFileSync(toolsPath, 'utf8'))
  const tools = fill(tpl.tools, { views, card_kinds: cardKinds, bundles })
  const toolsJson = JSON.stringify(tools)
  const catalogueSection =
    'Data views for query_data (observed values only):\n' +
    cat.views.map((v) => `- ${v.name}: ${v.grain}`).sort().join('\n')
  const system = readFileSync(systemPath, 'utf8').trim()
  for (const [name, text, limit] of [['tool schemas', toolsJson, LIMITS.tools], ['catalogue section', catalogueSection, LIMITS.catalogue], ['system.md', system, LIMITS.system]]) {
    if (est(text) > limit) throw new Error(`gen-tools: ${name} is ${est(text)} tokens, over the ${limit} budget`)
  }
  const prompt = `${system}\n\n${catalogueSection}`
  const src =
    `// GENERATED by worker/scripts/gen-tools.mjs from app/public/data/assistant/catalogue.json, index.json,\n` +
    `// app/src/assistant/prompt/system.md and tools.template.json. DO NOT EDIT. Regenerate: npm run gen-tools\n` +
    `export const CATALOGUE_VERSION = ${JSON.stringify(cat.catalogue_version)};\n` +
    `export const SYSTEM_PROMPT = ${JSON.stringify(prompt)};\n` +
    `export const TOOLS: unknown[] = ${JSON.stringify(tools, null, 2)};\n`
  return { src, tokens: { tools: est(toolsJson), catalogue: est(catalogueSection), system: est(system) }, catalogue_version: cat.catalogue_version }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const a = { data: join(ROOT, '../app/public/data'), system: join(ROOT, '../app/src/assistant/prompt/system.md'),
    tools: join(ROOT, '../app/src/assistant/prompt/tools.template.json'), playbook: join(ROOT, '../app/src/assistant/prompt/playbook.json'),
    out: join(ROOT, 'src/generated/tools.ts'), check: false }
  const argv = process.argv.slice(2)
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') a.check = true
    else if (['--data', '--system', '--tools', '--playbook', '--out'].includes(argv[i])) a[argv[i].slice(2)] = resolve(argv[++i])
    else { console.error(`unknown argument ${argv[i]}`); process.exit(2) }
  }
  const r = generate({ dataDir: a.data, systemPath: a.system, toolsPath: a.tools, playbookPath: a.playbook })
  if (a.check) {
    const cur = existsSync(a.out) ? readFileSync(a.out, 'utf8') : ''
    if (cur !== r.src) { console.error('gen-tools: generated file is stale; run npm run gen-tools'); process.exit(1) }
    console.log('gen-tools: up to date')
  } else {
    mkdirSync(dirname(a.out), { recursive: true })
    writeFileSync(a.out, r.src)
    console.log(`gen-tools: wrote ${a.out} (catalogue ${r.catalogue_version.slice(0, 12)}, tokens ${JSON.stringify(r.tokens)})`)
  }
}
